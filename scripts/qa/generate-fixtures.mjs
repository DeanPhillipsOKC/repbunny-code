#!/usr/bin/env node
// Issue #211: writes every QA test case's data file (scripts/qa/fixtures.mjs)
// to Google Drive through Google Drive for desktop, the same way
// scripts/Backup-Repo.ps1 finds it: "My Drive\RepBunny QA\Test data" on the
// first drive letter that has a "My Drive" folder. One subfolder per area. A
// refresh replaces files in place and removes ones no test case uses any more.
//
//   node scripts/qa/generate-fixtures.mjs [--out <folder>]
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { AREAS, JOURNEYS, TEST_CASES } from './procedure.mjs'
import { buildFixtureFiles, buildJourneyFiles } from './fixtures.mjs'

function findDriveRoot() {
  if (process.platform !== 'win32') return null
  for (const letter of 'CDEFGHIJKLMNOPQRSTUVWXYZ') {
    const myDrive = `${letter}:\\My Drive`
    if (existsSync(myDrive)) return join(myDrive, 'RepBunny QA')
  }
  return null
}

const args = process.argv.slice(2)
const outIndex = args.indexOf('--out')
const qaRoot = outIndex >= 0 ? args[outIndex + 1] : findDriveRoot()
if (!qaRoot) {
  console.error('Google Drive (a "My Drive" folder on any drive letter) was not found. Is Google Drive for desktop running and signed in? Or pass --out <folder>.')
  process.exit(1)
}
const dataRoot = outIndex >= 0 ? qaRoot : join(qaRoot, 'Test data')

const now = new Date()
const build = Number(execFileSync('git', ['rev-list', '--count', 'HEAD'], { encoding: 'utf8' }).trim())
const files = [...buildFixtureFiles(TEST_CASES, AREAS, now), ...buildJourneyFiles(JOURNEYS, now)]

// Built in full first, then written, so a failure never leaves half a set.
const wanted = new Map()
for (const f of files) wanted.set(join(dataRoot, f.folder, f.name), f.contents)

mkdirSync(dataRoot, { recursive: true })
if (outIndex < 0) mkdirSync(join(qaRoot, 'Builds'), { recursive: true })
for (const [path, contents] of wanted) {
  mkdirSync(join(path, '..'), { recursive: true })
  writeFileSync(path, contents)
}

// Remove files a test case no longer uses (only ones this script names).
let removed = 0
for (const folder of readdirSync(dataRoot, { withFileTypes: true }).filter((d) => d.isDirectory())) {
  for (const name of readdirSync(join(dataRoot, folder.name))) {
    const path = join(dataRoot, folder.name, name)
    const ours = /^TC-[A-Z]+-\d{3} .+\.(json|csv)$/.test(name) || folder.name === 'Journeys'
    if (ours && !wanted.has(path)) {
      rmSync(path)
      removed++
    }
  }
  if (readdirSync(join(dataRoot, folder.name)).length === 0) rmSync(join(dataRoot, folder.name), { recursive: true })
}

const stamp = now.toLocaleString('en-US', { dateStyle: 'medium', timeStyle: 'short' })
writeFileSync(
  join(dataRoot, 'README.txt'),
  [
    'RepBunny QA test data (issue #211)',
    '',
    `Made ${stamp} for build ${build}.`,
    `${files.length} files. Dates in them count back from the day they were made, so refresh before a run:`,
    '  npm run qa:fixtures',
    '',
    'Each test case on the QA page names the file to pick. Backups (.json) load with',
    'Account > Your data > Restore from a backup; Strong and Hevy files (.csv) with',
    'Import from another app. Restoring a full backup replaces everything on the phone,',
    'so use a test device or back up your own data first.',
    '',
    'Generated by scripts/qa/generate-fixtures.mjs. Edits here are overwritten.',
    '',
  ].join('\r\n'),
)

console.log(`Wrote ${files.length} files to ${dataRoot} (build ${build})${removed ? `, removed ${removed} old ones` : ''}`)
