import { test, expect } from '@playwright/test'
import { findReply, formatQuestion, MARKER, stripQuotedEmail } from '../scripts/ask-dean.mjs'

// Issue #227's ask-the-owner helper. No page needed (same "no separate
// unit-test runner" reasoning as client-error-log-unit.spec.ts).

const OWNER = 'DeanPhillipsOKC'
const BOT = 'github-actions[bot]'

function comment(author: string, body: string, createdAt = '2026-10-09T12:00:00Z') {
  return { author, body, createdAt }
}

test('options are lettered with the recommendation first', () => {
  const q = formatQuestion({ question: 'Which name?', context: 'Two options.', options: ['Routines', 'Plans', 'Programs'] })
  expect(q).toBe(
    'Which name?\n\nTwo options.\n\n' +
      '- **A (recommended):** Routines\n- **B:** Plans\n- **C:** Programs\n\n' +
      'Reply A, B, or C, plus any notes.',
  )
  expect(formatQuestion({ question: 'Pick', options: ['x', 'y'] })).toContain('Reply A or B, plus any notes.')
  expect(formatQuestion({ question: 'Ship it?' })).toBe('Ship it?')
  expect(() => formatQuestion({ question: ' ' })).toThrow()
})

test('the answer is the owner comments after the latest question', () => {
  const comments = [
    comment(BOT, `@${OWNER} Old question ${MARKER}`),
    comment(OWNER, 'Old answer'),
    comment(BOT, `@${OWNER} New question\n${MARKER}`, '2026-10-09T13:00:00Z'),
    comment('someone-else', 'Pick C!'),
    comment(OWNER, 'B', '2026-10-09T14:00:00Z'),
    comment(OWNER, 'and keep the old label', '2026-10-09T15:00:00Z'),
  ]
  const reply = findReply(comments, OWNER)
  expect(reply?.question).toBe(`@${OWNER} New question`)
  expect(reply?.askedAt).toBe('2026-10-09T13:00:00Z')
  expect(reply?.answer).toBe('B\n\nand keep the old label')
  expect(reply?.answeredAt).toBe('2026-10-09T15:00:00Z')
})

test('an email reply drops the quoted notification', () => {
  // Shape of the owner's real email reply on #227 (2026-10-09).
  const email =
    'A (got it)\r\n\r\nOn Fri, Oct 9, 2026, 4:15 PM github-actions[bot] ***@***.***>\r\nwrote:\r\n\r\n' +
    '> *github-actions[bot]* left a comment\r\n>\r\n>    - *A (recommended):* Yes, got it\r\n>'
  expect(stripQuotedEmail(email)).toBe('A (got it)')
  expect(stripQuotedEmail('B\n\nOn Fri, Oct 9 Someone wrote:\n> Q')).toBe('B')
  expect(stripQuotedEmail('C, and see below\n\n> quoted line\n> another')).toBe('C, and see below')
  // A plain reply, including one that mentions "on", is left alone.
  expect(stripQuotedEmail('On reflection, B.\nKeep the old label.')).toBe('On reflection, B.\nKeep the old label.')
  const reply = findReply([comment(BOT, `Q ${MARKER}`), comment(OWNER, email)], OWNER)
  expect(reply?.answer).toBe('A (got it)')
})

test('no question, or no reply yet', () => {
  expect(findReply([comment(OWNER, 'just a note')], OWNER)).toBeNull()
  // The owner quoting the marker doesn't count as a question.
  expect(findReply([comment(OWNER, `quoting ${MARKER}`)], OWNER)).toBeNull()
  const pending = findReply([comment(BOT, `Q ${MARKER}`), comment('someone-else', 'A')], OWNER)
  expect(pending?.answer).toBe('')
  expect(pending?.answeredAt).toBeNull()
})

test('a dated ask ends with the owner-date marker, and calendar records are never the answer', () => {
  // Issue #746.
  expect(formatQuestion({ question: 'Check egress?', options: ['Yes'], ownerDate: '2026-10-29T09:00 | check egress' })).toBe(
    'Check egress?\n\n- **A (recommended):** Yes\n\nReply A, plus any notes.\n\n<!-- owner-date: 2026-10-29T09:00 | check egress -->',
  )
  expect(() => formatQuestion({ question: 'Q', ownerDate: 'next week | x' })).toThrow()
  const reply = findReply(
    [
      comment(BOT, `Q ${MARKER}`),
      comment(OWNER, '<!-- calendar-synced: abc123 2026-10-29 -->\nCalendar: "RepBunny: x (#1)" is on the calendar.'),
      comment(OWNER, '<!-- calendar-removed: abc123 -->\nCalendar: removed.'),
    ],
    OWNER,
  )
  expect(reply?.answer).toBe('')
  expect(findReply([comment(BOT, `Q ${MARKER}`), comment(OWNER, 'A'), comment(OWNER, '<!-- calendar-synced: e1 2026-11-01 -->')], OWNER)?.answer).toBe('A')
})

test('agent comments posted as the owner are never the answer', () => {
  // Issue #1009.
  const footer = 'PR write-up\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'
  const reply = findReply(
    [comment(BOT, `Q ${MARKER}`), comment(OWNER, footer), comment(OWNER, '<!-- next-item hand-off -->\nIssue: #1'), comment(OWNER, '<!-- run-cost: 1 -->')],
    OWNER,
  )
  expect(reply?.answer).toBe('')
  expect(findReply([comment(BOT, `Q ${MARKER}`), comment(OWNER, footer), comment(OWNER, 'B, thanks')], OWNER)?.answer).toBe('B, thanks')
})
